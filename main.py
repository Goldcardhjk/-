"""进步壹号 Agent —— 桌面程序入口

运行：python main.py   （标准库 tkinter，无需额外安装依赖）
数据库：./data/agent.db （位于 D 盘项目目录）

启动流程（v0.69 启动优化）：
  1. App 先显示轻量加载页，再初始化数据库，避免启动早期窗口空白
  2. 优先构建关系网络首页；其余页签首次打开时再构建
  3. 需要选账号时，账号入口仍铺在主窗里（不再是独立登录窗）
  4. 选完账号原地进入主界面；「退出登录」也是原地回到账号入口
     ——全程只有一个窗口，不存在关窗再开窗的跳转
"""

import ui
from ui import App

# v0.61：真实启动时开启「近期提醒」弹窗（测试直接实例化 App 不受影响）
ui.STARTUP_POPUP = True


def main():
    # 数据库初始化移入 App 的加载阶段：先让窗口可见，再读取本地数据。
    # v0.66：不再 run_login 起独立窗口再销毁重建——App 自己负责账号入口。
    # 只要本机登记过账号，就先亮入口层；登记过就一定会亮，不再因单账号跳过。
    App(bootstrap_accounts=True).mainloop()


if __name__ == "__main__":
    main()
    # tkinter 在个别环境销毁根窗口后可能挂起无法退出；此时数据均已落库，
    # 直接强制结束进程，保证双击 exe 的用户点关闭就能退出
    import os
    os._exit(0)
